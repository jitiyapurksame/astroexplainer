// Generates project/exam-data.js from index.html (MODULES) + every built concept file.
// Usage: node tools/build_exam_data.js project     (re-run whenever concepts, exam questions or modules change)
const fs = require('fs'), path = require('path');
const dir = process.argv[2] || 'project';
const hub = fs.readFileSync(path.join(dir, 'index.html'), 'utf8');
const MODULES = eval('(' + hub.match(/const MODULES = (\[[\s\S]*?\n\]);/)[1] + ')');
function load(f) {
  const h = fs.readFileSync(path.join(dir, f), 'utf8');
  const m = h.match(/const CONCEPT = \{[\s\S]*?\n\};/);
  return eval('(' + m[0].replace('const CONCEPT = ', '').replace(/;$/, '') + ')');
}
const out = {};
for (const mod of MODULES) {
  const built = mod.concepts.filter(c => c.href);
  const concepts = built.map(c => {
    const C = load(c.href);
    if (C.id !== c.saveId) throw new Error(`${c.href}: CONCEPT.id ${C.id} != saveId ${c.saveId}`);
    const q = (C.examQuestions || [])[0];
    if (!q) throw new Error(`${c.href}: no exam question`);
    const subset = C.markPoints.filter(mp => q.markPoints.includes(mp.id));
    if (subset.length !== q.markPoints.length) throw new Error(`${c.href}: exam question references unknown mark point`);
    if (q.marks !== subset.length) console.warn(`note: ${c.href} marks=${q.marks} but ${subset.length} mark points (scoring uses mark points)`);
    return { id: C.id, icon: C.icon, title: C.title, href: c.href, prompt: q.prompt,
             markPoints: subset.map(mp => ({ id: mp.id, label: mp.label, terms: mp.terms })) };
  });
  out[mod.key] = { key: mod.key, title: mod.title, complete: built.length === mod.concepts.length && built.length > 0, concepts };
}
const js = '/* GENERATED by tools/build_exam_data.js - do not edit by hand. */\n' +
  'const ASTRO_EXAM_CONFIG = { passPct: 70, secondsPerQuestion: 180, maxQuestions: 8 };\n' +
  'const ASTRO_MODULES = ' + JSON.stringify(out, null, 1) + ';\n';
fs.writeFileSync(path.join(dir, 'exam-data.js'), js);
for (const k in out) console.log(k, out[k].title, '-', out[k].concepts.length, 'concepts, complete:', out[k].complete);
